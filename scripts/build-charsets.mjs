// Writes src/feeds/charsets.generated.ts: decoding tables for the legacy
// single-byte encodings (windows-1251, koi8-r, iso-8859-2, …) and the WHATWG
// label → encoding name map. Hermes has no TextDecoder for these, so the app
// decodes them from tables. Node's ICU TextDecoder is the source of truth.
//
// Run: node scripts/build-charsets.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let labels;
try {
  // Arrives with jsdom (a jest-expo dependency); only this script needs it.
  labels = require('whatwg-encoding/lib/labels-to-names.json');
} catch {
  console.error('whatwg-encoding is not installed; run npm install first.');
  process.exit(1);
}

const SINGLE_BYTE = /^(ibm866|iso-8859-\d+|koi8-[ru]|macintosh|windows-\d+|x-mac-cyrillic)$/;
// WHATWG labels this copy of whatwg-encoding leaves out. iso-8859-8-i is the
// same table as iso-8859-8 (it differs only in bidi handling).
const EXTRA_LABELS = {
  'iso-8859-8-i': 'iso-8859-8',
  csiso88598i: 'iso-8859-8',
  logical: 'iso-8859-8',
  'x-mac-cyrillic': 'x-mac-cyrillic',
  'x-mac-ukrainian': 'x-mac-cyrillic',
};
for (const [label, name] of Object.entries(EXTRA_LABELS)) labels[label] ??= name;
const labelMap = {};
const tables = {};
for (const [label, name] of Object.entries(labels)) {
  const canonical = name.toLowerCase();
  if (canonical === 'x-user-defined') continue;
  labelMap[label.toLowerCase()] = canonical;
  if (!SINGLE_BYTE.test(canonical) || tables[canonical]) continue;
  const bytes = Uint8Array.from({ length: 128 }, (_, i) => 0x80 + i);
  const decoded = new TextDecoder(canonical).decode(bytes);
  if (decoded.length !== 128) throw new Error(`${canonical}: expected 128 characters, got ${decoded.length}`);
  tables[canonical] = decoded;
}

// Invisible characters (C1 controls, no-break space, soft hyphen, …) are written as
// escapes so the generated source stays readable and diff-safe.
const visible = (json) => json.replace(/[\u0080-\u00a0\u00ad\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const out = `// Generated by scripts/build-charsets.mjs. Do not edit.

/** WHATWG encoding labels (lowercase) to canonical encoding names. */
export const ENCODING_LABELS: Record<string, string> = ${JSON.stringify(sorted(labelMap), null, 2)};

/** Characters for bytes 0x80–0xFF in each single-byte encoding (0x00–0x7F is ASCII). */
export const SINGLE_BYTE_TABLES: Record<string, string> = ${visible(JSON.stringify(sorted(tables), null, 2))};
`;
writeFileSync(join(root, 'src/feeds/charsets.generated.ts'), out);
console.log(`wrote ${Object.keys(tables).length} tables, ${Object.keys(labelMap).length} labels`);
