"""Subset the reader fonts to Latin woff2 and inline them as base64 for the article WebView.

Android WebView blocks file:// @font-face loads from an html-string source, so the
reader embeds fonts as data: URIs. Run with a Python that has fonttools + brotli:

    python scripts/build-reader-fonts.py
"""
import base64
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "node_modules" / "@expo-google-fonts"
OUT = ROOT / "src" / "reader" / "fonts.generated.ts"

# (css family, weight, style, path)
FACES = [
    ("Newsreader", 400, "normal", "newsreader/400Regular/Newsreader_400Regular.ttf"),
    ("Newsreader", 400, "italic", "newsreader/400Regular_Italic/Newsreader_400Regular_Italic.ttf"),
    ("Newsreader", 600, "normal", "newsreader/600SemiBold/Newsreader_600SemiBold.ttf"),
    ("Newsreader", 600, "italic", "newsreader/600SemiBold_Italic/Newsreader_600SemiBold_Italic.ttf"),
    ("Inter", 400, "normal", "inter/400Regular/Inter_400Regular.ttf"),
    ("Inter", 400, "italic", "inter/400Regular_Italic/Inter_400Regular_Italic.ttf"),
    ("Inter", 600, "normal", "inter/600SemiBold/Inter_600SemiBold.ttf"),
]

# Basic Latin, Latin-1, Latin Extended-A, general punctuation, currency, arrows.
UNICODES = "U+0000-00FF,U+0100-017F,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2190-2193,U+2212,U+2215"


def subset_woff2(path: pathlib.Path) -> bytes:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "calt", "onum", "lnum", "tnum", "frac"]
    options.name_IDs = []
    options.notdef_outline = True
    font = TTFont(path)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=subset.parse_unicodes(UNICODES))
    subsetter.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    rules = []
    total = 0
    for family, weight, style, rel in FACES:
        data = subset_woff2(FONTS / rel)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        rules.append(
            f"@font-face{{font-family:'{family}';font-weight:{weight};font-style:{style};"
            f"font-display:block;src:url(data:font/woff2;base64,{b64}) format('woff2');}}"
        )
    OUT.write_text(
        "// Generated by scripts/build-reader-fonts.py. Do not edit.\n"
        f"export const READER_FONT_FACES = {'`' + ''.join(rules) + '`'};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({total // 1024} KB of woff2)")


if __name__ == "__main__":
    main()
