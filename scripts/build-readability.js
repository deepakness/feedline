// Bundles Mozilla Readability into a string the hidden extractor WebView injects.
// Run after upgrading @mozilla/readability: node scripts/build-readability.js
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'node_modules', '@mozilla', 'readability');
const version = require(path.join(dir, 'package.json')).version;
const strip = (src) => src.replace(/^\s*if \(typeof module === "object"\) \{[\s\S]*?\n\}\s*$/m, '');
const source = [
  strip(fs.readFileSync(path.join(dir, 'Readability.js'), 'utf8')),
  strip(fs.readFileSync(path.join(dir, 'Readability-readerable.js'), 'utf8')),
].join('\n');

const out = path.join(root, 'src', 'extract', 'readability.generated.ts');
fs.writeFileSync(
  out,
  `// Generated by scripts/build-readability.js from @mozilla/readability ${version}. Do not edit.\n` +
    `export const READABILITY_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log(`wrote ${path.relative(root, out)} (${Math.round(source.length / 1024)} KB)`);
